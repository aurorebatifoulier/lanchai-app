import { TERMS_MARKDOWN, PRIVACY_MARKDOWN, CANCELLATION_TERMS_MARKDOWN, fillLegalPlaceholders } from '@/lib/legalContent';
import { SHOP_DISPLAY_DEFAULTS } from '@/functions/src/shared/shop';
import type { RetentionConfig } from '@/functions/src/shared/retention';
import { markdownToHtml, escHtml } from './markdownHtml';

// Public legal pages on Firebase Hosting (lanchai-app.firebaseapp.com/privacy, /terms,
// /cancellation) — needed by Google Play and App Store Connect. Built from the SAME texts as
// the app (lib/legalContent.ts, wording untouched) by `npm run legal:pages`; the values
// used for the placeholders are stored in the page (meta lanchai-legal-values) so
// tests/unit/legalPages.test.ts can prove each file is up to date with the texts.
// Placeholders: retention = config/legalPublic (read by the script), address = the
// shop's default address (SHOP_DISPLAY_DEFAULTS), WhatsApp line omitted (config/shop isn't
// public) — the contact email stays.

export const LEGAL_PAGES = [
  { file: 'privacy.html', path: '/privacy', title: 'Privacy policy', markdown: PRIVACY_MARKDOWN },
  { file: 'terms.html', path: '/terms', title: 'Terms of service', markdown: TERMS_MARKDOWN },
  { file: 'cancellation.html', path: '/cancellation', title: 'Cancellation policy', markdown: CANCELLATION_TERMS_MARKDOWN },
] as const;

export type LegalPage = (typeof LEGAL_PAGES)[number];

export function buildLegalPage(page: LegalPage, retention: RetentionConfig): string {
  const body = markdownToHtml(
    fillLegalPlaceholders(page.markdown, { ...SHOP_DISPLAY_DEFAULTS, whatsappNumber: '' }, retention),
    { title: 'h1', sectionTag: 'h2' },
  );
  const nav = LEGAL_PAGES.map(p => p.path === page.path
    ? `<span aria-current="page">${escHtml(p.title)}</span>`
    : `<a href="${p.path}">${escHtml(p.title)}</a>`).join('');
  const values = JSON.stringify({ idRetentionMonths: retention.idRetentionMonths, proofRetentionDays: retention.proofRetentionDays });
  return `<!doctype html>
<!-- Generated by \`npm run legal:pages\` from lib/legalContent.ts — do not edit by hand. -->
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<meta name="lanchai-legal-values" content='${values}'/>
<title>${escHtml(page.title)} · LANCHAI</title>
<style>
  :root { --amber: #F4B400; --carbon: #1E1E1E; --cream: #FAFAF7; --muted: #6B6B6B; --border: #ECECEA; }
  * { box-sizing: border-box; }
  body { margin: 0; background: var(--cream); color: var(--carbon); font: 16px/1.6 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; }
  header { background: #fff; border-bottom: 1px solid var(--border); }
  .bar { max-width: 760px; margin: 0 auto; padding: 14px 16px; display: flex; align-items: center; gap: 10px; flex-wrap: wrap; }
  .brand { font-weight: 800; font-size: 20px; letter-spacing: -0.5px; margin-right: auto; }
  .brand span { box-shadow: inset 0 -0.45em 0 var(--amber); }
  nav { display: flex; gap: 6px; flex-wrap: wrap; }
  nav a, nav span { font-size: 14px; padding: 6px 12px; border-radius: 999px; text-decoration: none; color: var(--carbon); border: 1px solid var(--border); background: #fff; }
  nav span { background: var(--amber); border-color: var(--amber); font-weight: 600; }
  main { max-width: 760px; margin: 0 auto; padding: 24px 16px 48px; }
  .card { background: #fff; border: 1px solid var(--border); border-radius: 18px; padding: 24px 20px; }
  h1 { font-size: 24px; line-height: 1.3; margin: 0 0 16px; }
  h2 { font-size: 17px; margin: 28px 0 8px; }
  p { margin: 0 0 10px; }
  ul { margin: 4px 0 12px; padding-left: 22px; } li { margin: 4px 0; } li.sub { margin-left: 18px; list-style: circle; }
  hr { border: none; border-top: 1px solid var(--border); margin: 20px 0; }
  em { color: var(--muted); }
  footer { max-width: 760px; margin: 0 auto; padding: 0 16px 40px; color: var(--muted); font-size: 14px; }
  footer a { color: var(--carbon); }
</style>
</head>
<body>
<header><div class="bar"><div class="brand"><span>LANCHAI</span></div><nav>${nav}</nav></div></header>
<main><article class="card">
${body}
</article></main>
<footer>Questions? <a href="mailto:contact@lanchai.la">contact@lanchai.la</a></footer>
</body>
</html>
`;
}

/** The placeholder values stored in a generated page (for the up-to-date test). */
export function legalValuesOf(html: string): RetentionConfig | null {
  const m = /<meta name="lanchai-legal-values" content='([^']+)'/.exec(html);
  if (!m) return null;
  try { return JSON.parse(m[1]) as RetentionConfig; } catch { return null; }
}
